"""
timingtask.rl: reinforcement learning on the timing task.

The agent is a recurrent network with a policy head and a value head. At each
step it emits a lick probability, acts, and receives the reward defined by the
task. Training follows Song, Yang and Wang (2017): REINFORCE with a learned
value baseline, and no target lick time anywhere in the objective.

Policy
------
The policy produces two logits per step. With ``P(lick at t) = sigmoid(z_lick -
z_wait)`` the per-step lick probability is a discrete-time hazard, and the
lick time is its first passage. A rising logit gap is therefore equivalent to
a ramp crossing a threshold, with the lick-time distribution generated by the
network dynamics rather than parameterised.

Episodes
--------
One episode is one trial. Information about previous trials reaches the policy
through the previous-trial observation channels, which are held constant for
the whole trial, so the hidden state is reset at every trial boundary and
backpropagation through time spans a single trial. The generator's own state
(delay schedule, outcome history, history channels) persists across episodes.

Diagnostics
-----------
``p_engaged`` (fraction of cued trials with a lick) and ``p_correct``
(fraction of licked trials that were rewarded) are reported separately, since
a policy that never licks makes no errors.
"""
from __future__ import annotations

import math
from typing import Any, Callable, Dict, List, Optional

import numpy as np
import torch
import torch.nn as nn
from torch import Tensor
from torch.distributions import Categorical

from .config import ObservationConfig, SchedulerConfig, TimingTaskConfig, make_config
