"""
timingtask.rl — reinforcement learning on the timing task.
=======================================================================

The network is never told when to lick. It emits a per-step lick probability,
acts, and learns only from reward. Following Song, Yang & Wang 2017 (eLife
6:e21492): a recurrent policy, REINFORCE with a LEARNED VALUE BASELINE, and no
shaping beyond what the task itself provides.

WHY A PER-STEP BERNOULLI IS ALSO A RAMP-TO-BOUND
------------------------------------------------
Policy gradient needs a stochastic policy; the timing literature wants a ramp
crossed against a threshold. These are the same object. The policy emits a
logit z(t); P(lick at t) = sigmoid(z(t)) is a HAZARD RATE, and the realised lick
time is the first passage of that hazard. A rising z is a ramp, the sigmoid's
midpoint is the threshold, and the lick-time distribution is generated by the
dynamics rather than parameterised -- which is the point. Nothing prescribes t*.

EPISODE = ONE TRIAL
-------------------
Cross-trial information reaches the policy through the previous-trial
observation channels, held constant for the whole trial, so the recurrent state
does not have to bridge trials. BPTT is then ~150 steps rather than thousands.
The generator's own state (the delay schedule, the outcome history, the history
ring) still persists across episodes -- only the network's hidden state resets.

THE FAILURE MODE TO WATCH
-------------------------
Song et al.'s networks can settle into never acting, because their reward for
correct withholding is exactly 0. That does NOT apply unchanged here: this task
charges ``time_penalty`` every step, so waiting is strictly expensive. Track ``p_engaged`` and
``p_correct`` separately anyway -- a single accuracy number cannot tell an agent
that times well from one that does nothing.
"""
