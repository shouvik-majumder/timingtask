def summarise_by_delay(records: List[Dict[str, Any]], *,
                       max_rows: int = 8) -> Dict[str, Any]:
    """Split trials by required delay and report first-lick statistics.

    Because a trial ends at ``delay + answer_window``, longer delays admit
    later licks, so the raw mean first-lick time is not comparable across
    delays. ``first_lick_cut`` averages only licks earlier than ``cut``, the
    deadline of the shortest trial in the set. ``tracking`` is the slope of
    ``first_lick_cut`` against the delay: 1 indicates the lick time follows
    the delay, 0 a fixed interval.

    Delays are binned into at most ``max_rows`` groups when more distinct
    values are present.
    """
    cued = [r for r in records if not r.get("no_cue_trial")]
    if not cued:
        return dict(cut=float("nan"), rows=[], tracking=float("nan"))
    cut = min(float(r["delay"]) + float(r.get("answer_window", 0.0))
              for r in cued)
    delays = sorted({round(float(r["delay"]), 2) for r in cued})
    width = 0.0
    if len(delays) > max_rows:
        width = (delays[-1] - delays[0]) / max_rows or 0.1
    groups: Dict[float, list] = {}
    for r in cued:
        d = float(r["delay"])
        key = (round(delays[0] + width * int((d - delays[0]) / width), 2)
               if width else round(d, 2))
        groups.setdefault(key, []).append(r)
    rows = []
    for d in sorted(groups):
        g = groups[d]
        fl = np.array([r["first_lick_s"] for r in g
                       if r.get("first_lick_s") is not None], float)
        sub = fl[fl < cut]
        rows.append(dict(
            delay=d, n=len(g), p_lick=len(fl) / len(g),
            first_lick=float(fl.mean()) if len(fl) else float("nan"),
            first_lick_cut=float(sub.mean()) if len(sub) else float("nan"),
            n_cut=int(len(sub)),
            p_correct=float(np.mean([bool(r.get("rewarded")) for r in g])),
            p_early=float(np.mean([bool(r.get("early")) for r in g]))))
    tracking = float("nan")
    good = [r for r in rows if r["n_cut"] >= 20]
    if len(good) > 1:
        x = np.array([r["delay"] for r in good], float)
        y = np.array([r["first_lick_cut"] for r in good], float)
        if x.std() > 0:
            tracking = float(np.polyfit(x, y, 1)[0])
    return dict(cut=cut, rows=rows, tracking=tracking, binned=bool(width))


def format_delay_report(rep: Dict[str, Any], label: str = "",
                        indent: str = "    ") -> str:
    """Format the output of :func:`summarise_by_delay` as a text table."""
    if not rep["rows"]:
        return f"{indent}{label}: no cued trials"
    L = [f"{indent}{label} by delay "
         f"(first lick capped at {rep['cut']:.2f}s, the shortest trial's "
         f"deadline"
         + ("; delays binned)" if rep.get("binned") else ")"),
         f"{indent}  {'delay':>6s} {'n':>6s} {'p(lick)':>8s} {'FL':>7s} "
         f"{'FL_cut':>7s} {'n_cut':>6s} {'corr':>6s} {'early':>6s}"]
    for r in rep["rows"]:
        L.append(f"{indent}  {r['delay']:6.2f} {r['n']:6d} {r['p_lick']:8.2f} "
                 f"{r['first_lick']:7.3f} {r['first_lick_cut']:7.3f} "
                 f"{r['n_cut']:6d} {r['p_correct']:6.2f} {r['p_early']:6.2f}")
    L.append(f"{indent}  tracking slope d(FL_cut)/d(delay) = "
             f"{rep['tracking']:+.3f}   (1 = follows the delay, 0 = fixed "
             f"interval)")
    return "\n".join(L)


def summarise(records: List[Dict[str, Any]]) -> Dict[str, float]:
    """Behavioural summary of a set of trial records.

    ``p_engaged`` and ``p_correct`` are reported separately: a policy that
    never licks makes no errors, so a single accuracy figure cannot
    distinguish accurate timing from inaction.
    """
    cued = [r for r in records if not r.get("no_cue_trial")]
    if not cued:
        return dict(p_engaged=0., p_correct=0., p_early=0., p_miss=0.,
                    p_iti_lick=float("nan"), n_iti_licks=float("nan"),
                    p_cue_success=float("nan"),
                    delay=float("nan"), value_gain=float("nan"),
                    reward_rate=float("nan"),
                    first_lick=float("nan"), n=0)
    licked = [r for r in cued if r.get("decisive_lick_s") is not None]
    rew = [r for r in cued if r.get("rewarded")]
    fl = [r["first_lick_s"] for r in cued if r.get("first_lick_s") is not None]
    return dict(
        p_engaged=len(licked) / len(cued),
        p_correct=len(rew) / max(len(licked), 1),
        p_early=sum(bool(r.get("early")) for r in cued) / len(cued),
        p_miss=sum(bool(r.get("miss")) for r in cued) / len(cued),
        # ITI licking is computed over all trials, including catch trials,
        # since the stop-licking period is identical on both.
        p_iti_lick=sum(bool(r.get("iti_licked")) for r in records) / len(records),
        n_iti_licks=float(np.mean([r.get("n_iti_licks", 0) for r in records])),
        # Matches the scheduler's definition: an early lick does not count as
        # a cue response.
        p_cue_success=(sum(bool(r.get("cue_success")) and not r.get("early")
                           for r in cued) / len(cued)),
        delay=float(np.mean([r["delay"] for r in cued])),
        value_gain=float(np.mean([r.get("value_gain", 1.0) for r in cued])),
        reward_rate=float(np.mean([r.get("reward_rate", float("nan"))
                                   for r in cued])),
        first_lick=float(np.mean(fl)) if fl else float("nan"),
        n=len(cued))
